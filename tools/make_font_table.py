"""Character width table generator: a font's widths as a Python module in smiles2pptx/fonts/.

Development tool only: it needs fontTools, which the package itself does not use.

Usage:
    python tools/make_font_table.py <font file> <font name> <module name>
Example:
    python tools/make_font_table.py C:/Windows/Fonts/arial.ttf Arial arial
"""
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]

# Characters that drawings and reaction condition text may use.
RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00FF),  # Latin-1 (degree sign, middle dot, plus-minus, micro sign)
    (0x0391, 0x03A1),  # Greek capitals (U+03A2 is not a character)
    (0x03A3, 0x03A9),
    (0x03B1, 0x03C9),  # Greek small letters
]
EXTRA = [
    0x2009,  # thin space
    0x2013, 0x2014,  # en dash, em dash
    0x2022, 0x2026,  # bullet, ellipsis
    0x2032, 0x2033,  # prime, double prime
    0x2190, 0x2192,  # arrows
    0x2212,  # minus sign
    0x2261,  # identical to (triple bond in text)
]


def main(font_file, font_name, module):
    font = TTFont(font_file)
    upm = font["head"].unitsPerEm
    os2 = font["OS/2"]
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    codes = [c for a, b in RANGES for c in range(a, b + 1)] + EXTRA
    widths = {c: hmtx[cmap[c]][0] for c in codes if c in cmap}
    missing = [c for c in codes if c not in cmap]
    letters = [widths[c] for c in range(0x41, 0x5B)] + [widths[c] for c in range(0x61, 0x7B)]
    fallback = round(sum(letters) / len(letters))
    version = font["name"].getDebugName(5) or ""

    lines = []
    row = []
    for c in sorted(widths):
        row.append(f"0x{c:04X}: {widths[c]}")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    text = (
        f'"""Character widths of {font_name}, in font units.\n\n'
        f"Generated by tools/make_font_table.py from the font file ({version}).\n"
        'Do not edit by hand; run the tool again instead.\n"""\n\n'
        f"NAME = {font_name!r}\n"
        f"UNITS_PER_EM = {upm}\n"
        f"CAP_HEIGHT = {os2.sCapHeight}\n"
        f"ASCENT = {os2.usWinAscent}\n"
        f"DESCENT = {os2.usWinDescent}\n"
        f"FALLBACK_WIDTH = {fallback}  # average of A-Z and a-z, for characters not in the table\n\n"
        "WIDTHS = {\n" + "\n".join(lines) + "\n}\n"
    )
    out = ROOT / "smiles2pptx" / "fonts" / f"{module}.py"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT)}: {len(widths)} characters"
          + (f", not in the font: {', '.join(f'U+{c:04X}' for c in missing)}" if missing else ""))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
